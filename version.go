package mos

// Version 是 MoS 框架的版本号（源码树版本）。
//
// **约定**：
//
//   - main 上的值 = **下一个待发布版本**（v0.1.0 已发布并打了标签，main
//     上的开发算 v0.2.0）；发布时打同名标签，**常量与标签一字不差**
//     （发 v0.2.0 就打 `v0.2.0`，不改这个值）；发布之后把常量推到下一版
//     （0.3.0）继续开发；
//   - 因此 `go get` 到某个标签的外部工程，拿到的是**那个标签当时**的常量；
//     `go get ...@main` 拿到的是"正在开发的版本"。
//
// 与 Go 模块惯例的差异：模块版本属于标签、不属于代码（`go list -m` 才是
// 权威版本）。这里额外留一份常量，是为了让宿主能把框架版本写进日志与
// 装配快照（`Describe()` 会打印它）——代价是发版时多一处要对齐的地方，
// 所以**发版检查清单里必须有"常量 == 标签名"这一条**。
const Version = "0.2.0"
